import { writeFile } from 'node:fs/promises';

const raw = (process.env.MOBILE_API_BASE_URL || '').trim().replace(/\/$/, '');
if (raw) {
  let parsed;
  try { parsed = new URL(raw); } catch { throw new Error('MOBILE_API_BASE_URL must be a valid absolute URL.'); }
  const localHost = ['localhost', '127.0.0.1'].includes(parsed.hostname);
  if (parsed.protocol !== 'https:' && !(localHost && parsed.protocol === 'http:')) {
    throw new Error('MOBILE_API_BASE_URL must use HTTPS except for localhost development.');
  }
}
const output = `// Generated by tools/configure-mobile.mjs. Do not commit production endpoints or secrets here.\nwindow.SD_DEFAULT_API_BASE = ${JSON.stringify(raw)};\n`;
await writeFile(new URL('../frontend/runtime-config.js', import.meta.url), output, 'utf8');
console.log(raw ? `Mobile API endpoint configured: ${new URL(raw).origin}` : 'No mobile API endpoint set; users can enter the server URL in the app login screen.');
